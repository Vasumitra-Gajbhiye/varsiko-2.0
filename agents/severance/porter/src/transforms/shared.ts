import { readFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ts, type SourceFile } from 'ts-morph';
import type { Finding } from '../inventory/schema.js';
import { exists, readText } from '../util/fs.js';
import type { ProjectLayout, TransformContext } from './types.js';

const here = dirname(fileURLToPath(import.meta.url));

/**
 * Templates live outside `src/` so they are never compiled — they are source
 * text Porter copies into somebody else's repo. Resolve them relative to the
 * built file, walking up out of `dist/transforms`.
 */
export async function template(relativePath: string): Promise<string> {
  const roots = [
    resolve(here, '../../templates'),
    resolve(here, '../../../templates'),
  ];
  for (const root of roots) {
    try {
      return await readFile(resolve(root, relativePath), 'utf8');
    } catch {
      continue;
    }
  }
  throw new Error(`Porter template not found: ${relativePath}`);
}

/** Marker every generated source file starts with. Used to skip our own output. */
export const GENERATED_MARKER = '// Generated by Porter';

/**
 * Prepend the provenance header every generated file carries.
 *
 * A reviewer opening an unfamiliar file in their own repo should learn, in the
 * first three lines, what wrote it and what it replaced. Generated code that
 * does not say it is generated is how codemods lose people's trust.
 */
export function stamp(contents: string, replaces: string): string {
  const header = [
    `${GENERATED_MARKER} (Severance agent 03).`,
    `// Replaces: ${replaces}`,
    '// Review this file as you would any dependency you are about to own.',
    '',
  ].join('\n');
  return header + contents;
}

/**
 * Source files of the app being ported. Excludes dependencies, build output and
 * anything Porter itself generated — a transform that re-reads its own shims
 * would "fix" them on the next pass.
 */
export function appSourceFiles(ctx: TransformContext): SourceFile[] {
  return ctx.project.getSourceFiles().filter((file) => {
    const path = file.getFilePath();
    if (path.includes('/node_modules/')) return false;
    if (path.includes('/.next/')) return false;
    if (file.getFullText().startsWith(GENERATED_MARKER)) return false;
    return true;
  });
}

/** All distinct files named by a set of findings. */
export function filesOf(findings: Finding[]): string[] {
  const set = new Set<string>();
  for (const finding of findings) {
    for (const evidence of finding.evidence) set.add(evidence.file);
  }
  return [...set].sort();
}

/** Findings of a kind whose evidence names one of the given import specifiers. */
export function findingsMatching(findings: Finding[], specifiers: string[]): Finding[] {
  return findings.filter((finding) =>
    finding.evidence.some((e) =>
      specifiers.some((s) => e.matched === s || e.matched.startsWith(s + '/')),
    ),
  );
}

