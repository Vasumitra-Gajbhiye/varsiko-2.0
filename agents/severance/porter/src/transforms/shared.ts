/** Directory `@/*` points at, relative to the repo ('' or 'src'), or null if unmapped. */
function readAliasRoot(root: string): string | null {
  for (const name of ['tsconfig.json', 'jsconfig.json']) {
    const configPath = join(root, name);
    if (!ts.sys.fileExists(configPath)) continue;

    // TypeScript's own reader understands comments, trailing commas and
    // `extends`, all of which real tsconfig files use and JSON.parse rejects.
    const read = ts.readConfigFile(configPath, ts.sys.readFile);
    if (read.error) continue;
    const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, root, undefined, configPath);

    const targets = parsed.options.paths?.['@/*'];
    if (!targets || targets.length === 0) continue;

    const base = (parsed.options.pathsBasePath as string | undefined) ?? root;
    const first = targets[0]!.replace(/\/?\*$/, '');
    const relDir = relative(root, resolve(base, first)).split(sep).join('/');
    if (relDir.startsWith('..')) continue;
    return relDir;
  }
  return null;
}

export async function resolveLayout(repoRoot: string): Promise<ProjectLayout> {
  const root = resolve(repoRoot);

  const rootApp = await exists(join(root, 'app'));
  const rootPages = await exists(join(root, 'pages'));
  const srcApp = await exists(join(root, 'src', 'app'));
  const srcPages = await exists(join(root, 'src', 'pages'));

  // Next.js prefers a root `app`/`pages` over `src/` when both exist.
  const srcRoot: ProjectLayout['srcRoot'] = rootApp || rootPages ? '' : srcApp || srcPages ? 'src' : '';
  const appDir = rootApp ? 'app' : srcApp ? 'src/app' : null;

  const aliasRoot = readAliasRoot(root);
  const libBase = aliasRoot ?? srcRoot;
  const libDir = `${libBase ? libBase + '/' : ''}lib/porter`;

  // Line endings and indentation are sampled from the config, which every Next
  // repo has and which Porter is about to edit. Matching them keeps the diff to
  // the lines that actually changed.
  let sample = '';
  for (const name of ['next.config.mjs', 'next.config.js', 'next.config.ts', 'next.config.cjs', 'package.json']) {
    const text = await readText(join(root, name));
    if (text) {
      sample = text;
      break;
    }
  }
  const crlf = sample.includes('\r\n');
  const indented = sample.split(/\r?\n/).filter((line) => /^\s+\S/.test(line));
  const tabs = indented.filter((line) => line.startsWith('\t')).length;
  const fours = indented.filter((line) => /^ {4}\S/.test(line)).length;
  const twos = indented.filter((line) => /^ {2}\S/.test(line)).length;
  const indent: ProjectLayout['indent'] = tabs > twos && tabs > fours ? 'tab' : fours > twos ? 'four' : 'two';

  return { srcRoot, appDir, aliasRoot, libDir, crlf, indent };
}

/**
 * The import specifier a call site should use to reach a generated module.
 *
 * Aliased repos get `@/lib/porter/<module>`. Everyone else gets a relative path
 * computed from the importing file, which is uglier but always resolves.
 */
export function libImport(
  layout: ProjectLayout,
  repoRoot: string,
  fromFile: string,
  moduleName: string,
): string {
  if (layout.aliasRoot !== null) return `@/lib/porter/${moduleName}`;

  const target = join(repoRoot, layout.libDir, moduleName);
  let spec = relative(dirname(fromFile), target).split(sep).join('/');
  if (!spec.startsWith('.')) spec = './' + spec;
  return spec;
}

/** Convenience wrapper used by transforms, which always hold a context. */
export function importFor(ctx: TransformContext, file: SourceFile, moduleName: string): string {
  return libImport(ctx.layout, ctx.repoRoot, file.getFilePath(), moduleName);
}

/** Repo-relative path of a generated module file. */
export function libPath(layout: ProjectLayout, relativePath: string): string {
  return `${layout.libDir}/${relativePath}`;
}
