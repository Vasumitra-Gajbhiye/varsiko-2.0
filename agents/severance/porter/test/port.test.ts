import assert from 'node:assert/strict';
import { test } from 'node:test';
import { cp, mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanRepo } from '../src/inventory/scan.js';
import { portRepo } from '../src/runtime/port.js';

const FIXTURE = resolve(dirname(fileURLToPath(import.meta.url)), '../fixtures/victim-app');

async function fixtureCopy(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), 'porter-port-'));
  const app = join(dir, 'app-under-test');
  await cp(FIXTURE, app, { recursive: true });
  return app;
}

const read = (root: string, path: string) => readFile(join(root, path), 'utf8');

test('ports the fixture, then has nothing left to do', async (t) => {
  const root = await fixtureCopy();
  t.after(() => rm(dirname(root), { recursive: true, force: true }));

  const first = await portRepo(root, { writeArtifacts: false });
  assert.ok(first.plan.steps.length >= 7, `expected the full set of steps, got ${first.plan.steps.length}`);
  assert.ok(first.diff.includes('diff --git'), 'expected a git-style diff');
  assert.equal(first.applied, true);

  // Every finding is either fixed or reported; nothing is silently dropped.
  const unhandledKinds = first.plan.unhandled.map((f) => f.kind);
  assert.deepEqual(unhandledKinds, [], `unexpected unhandled findings: ${unhandledKinds.join(', ')}`);

  // Idempotency: the second run finds nothing to do and writes nothing.
  const second = await portRepo(root, { writeArtifacts: false });
  assert.equal(second.plan.steps.length, 0, 'second run should be a no-op');
  assert.equal(second.diff, '');

  // And a fresh scan agrees the repo is clean.
  assert.deepEqual((await scanRepo(root)).findings, []);
});

test('rewrites imports to the shims it actually writes', async (t) => {
  const root = await fixtureCopy();
  t.after(() => rm(dirname(root), { recursive: true, force: true }));
  await portRepo(root, { writeArtifacts: false });

  assert.match(await read(root, 'lib/rate-limit.ts'), /from '@\/lib\/porter\/kv'/);
  assert.match(await read(root, 'lib/storage.ts'), /from '@\/lib\/porter\/storage'/);
  assert.match(await read(root, 'app/gallery/page.tsx'), /from '@\/lib\/porter\/storage\/client'/);
  // handleUpload runs on the server even though it is imported from /client.
  assert.match(await read(root, 'app/api/upload/route.ts'), /from '@\/lib\/porter\/storage\/handle-upload'/);
  assert.match(await read(root, 'middleware.ts'), /from '@\/lib\/porter\/request-context'/);

  for (const shim of [
    'lib/porter/kv/index.ts',
    'lib/porter/storage/index.ts',
    'lib/porter/storage/client.ts',
    'lib/porter/storage/handle-upload.ts',
    'lib/porter/request-context.ts',
    'lib/porter/edge-config.ts',
  ]) {
    assert.match(await read(root, shim), /^\/\/ Generated by Porter/, `${shim} should be generated and stamped`);
  }

  const pkg = JSON.parse(await read(root, 'package.json'));
  for (const gone of ['@vercel/kv', '@vercel/blob', '@vercel/analytics', '@vercel/speed-insights']) {
    assert.ok(!pkg.dependencies[gone], `${gone} should be removed`);
  }
  assert.ok(pkg.dependencies['ioredis'] && pkg.dependencies['sharp'] && pkg.dependencies['@aws-sdk/client-s3']);
});

test('keeps the revalidate contract and drops only edge pins', async (t) => {
  const root = await fixtureCopy();
  t.after(() => rm(dirname(root), { recursive: true, force: true }));
  await portRepo(root, { writeArtifacts: false });

  // Freshness settings are the app's own contract and must survive the port.
  assert.match(await read(root, 'app/page.tsx'), /export const revalidate = 3600/);
  assert.match(await read(root, 'app/products/[slug]/page.tsx'), /export const revalidate = 600/);
  // Edge pins are what actually has to go.
  assert.ok(!(await read(root, 'app/api/geo/route.ts')).includes("runtime = 'edge'"));
  assert.ok(!(await read(root, 'middleware.ts')).includes("runtime: 'edge'"));
  // The matcher next to the removed pin is untouched.
  assert.match(await read(root, 'middleware.ts'), /matcher:/);
});

