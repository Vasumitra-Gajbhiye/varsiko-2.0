test('adapts to a src/ layout with no path alias', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'porter-src-'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  await mkdir(join(dir, 'src/app'), { recursive: true });
  await writeFile(join(dir, 'package.json'), JSON.stringify({ name: 'a', dependencies: { next: '15.1.0', '@vercel/kv': '^3' } }), 'utf8');
  await writeFile(join(dir, 'next.config.mjs'), 'export default {};', 'utf8');
  await writeFile(join(dir, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true } }), 'utf8');
  await writeFile(join(dir, 'src/app/page.tsx'), "import { kv } from '@vercel/kv';\nexport default function P() { return null }\n", 'utf8');

  await portRepo(dir, { writeArtifacts: false });

  // Shims land under src/, and without an alias the import must be relative.
  assert.match(await read(dir, 'src/lib/porter/kv/index.ts'), /^\/\/ Generated by Porter/);
  assert.match(await read(dir, 'src/app/page.tsx'), /from '\.\.\/lib\/porter\/kv'/);
});

test('leaves a computed next.config alone and says so', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'porter-computed-'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  await mkdir(join(dir, 'app'), { recursive: true });
  await writeFile(join(dir, 'package.json'), JSON.stringify({ name: 'a', dependencies: { next: '15.1.0' } }), 'utf8');
  await writeFile(join(dir, 'next.config.mjs'), 'const build = () => ({});\nexport default build();\n', 'utf8');
  await writeFile(join(dir, 'app/page.tsx'), 'export const revalidate = 60;\nexport default function P() { return null }\n', 'utf8');

  const { plan } = await portRepo(dir, { writeArtifacts: false });
  const isr = plan.steps.find((s) => s.id === 'isr');

  assert.ok(isr, 'the ISR step should still run');
  assert.equal(await read(dir, 'next.config.mjs'), 'const build = () => ({});\nexport default build();\n');
  assert.ok(isr!.caveats.some((c) => /[Cc]ould not wire/.test(c)), 'should warn that it could not wire the handler');
  // It could not fix it, so it must not claim it.
  assert.ok(plan.unhandled.some((f) => f.kind === 'isr'), 'the unfixed ISR finding should be reported');
});
