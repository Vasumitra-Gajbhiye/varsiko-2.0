test('a dry run reports the real diff and changes nothing on disk', async (t) => {
  const root = await fixtureCopy();
  t.after(() => rm(dirname(root), { recursive: true, force: true }));

  const before = await read(root, 'lib/rate-limit.ts');
  const dry = await portRepo(root, { dryRun: true });

  assert.equal(dry.applied, false);
  assert.ok(dry.diff.includes('diff --git'), 'a dry run should still produce a diff');
  assert.ok(dry.touched.includes('package.json'));
  assert.equal(dry.plan.repoRoot, resolve(root), 'the plan should describe the real repo');
  assert.equal(await read(root, 'lib/rate-limit.ts'), before, 'dry run must not write');

  await assert.rejects(() => read(root, 'lib/porter/kv/index.ts'));
});

test('moves crons out of vercel.json into a schedule the runner understands', async (t) => {
  const root = await fixtureCopy();
  t.after(() => rm(dirname(root), { recursive: true, force: true }));
  await portRepo(root, { writeArtifacts: false });

  const vercelJson = JSON.parse(await read(root, 'vercel.json'));
  assert.ok(!vercelJson.crons, 'crons should be gone');
  assert.ok(vercelJson.functions, 'unrelated keys should survive');

  const manifest = JSON.parse(await read(root, 'infra/porter-schedules.json'));
  assert.equal(manifest.jobs.length, 2);
  assert.deepEqual(manifest.jobs.map((j: { schedule: string }) => j.schedule), ['0 9 * * *', '*/15 * * * *']);
  for (const job of manifest.jobs) {
    assert.match(job.url, /^\$\{PUBLIC_BASE_URL\}\/api\/cron\//);
    assert.equal(job.headers.authorization, 'Bearer ${CRON_SECRET}');
  }
  assert.match(await read(root, 'infra/scheduler.mjs'), /startScheduler/);
});

